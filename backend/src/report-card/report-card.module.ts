import { Logger, Module, type DynamicModule } from '@nestjs/common';
import { BullModule } from '@nestjs/bullmq';
import { StudentPortalModule } from '@/student-portal/student-portal.module';
import { QUEUE_REPORT_CARD_GENERATE } from './report-card.constants';
import { ReportDataService } from './report-data.service';
import { ReportGenerationService } from './report-generation.service';
import { ReportGenerationScheduler } from './report-generation.scheduler';
import { ReportCommentService } from './report-comment.service';
import { ReportReleaseService } from './report-release.service';
import { StudentReportsService } from './student-reports.service';
import { ReportCardProcessor } from './report-card.processor';
import { ReportCommentController } from './report-comment.controller';
import { ReportReleaseController } from './report-release.controller';
import { PortalReportController } from './portal-report.controller';
import { ReportLinkController } from './report-link.controller';

/**
 * Report cards and transcripts (feature `report_cards`). With Redis
 * (USE_REDIS=true and REDIS_URL, the same switch as QueueModule, whose
 * BullModule.forRoot connection this shares) PDFs are generated by the
 * `report-card-generate` BullMQ queue; otherwise in-process after the
 * publish request answers. ReportGenerationScheduler resumes generation a
 * restart left behind. Exports StudentReportsService for the parent portal.
 *
 * forRoot() returns one cached module, so importing it from another module
 * (the parent portal) shares the same providers and registers controllers
 * once.
 */
@Module({})
export class ReportCardModule {
  private static instance?: DynamicModule;

  static forRoot(): DynamicModule {
    ReportCardModule.instance ??= ReportCardModule.build();
    return ReportCardModule.instance;
  }

  private static build(): DynamicModule {
    const useRedis = process.env.USE_REDIS === 'true' && !!process.env.REDIS_URL;
    if (!useRedis) {
      new Logger(ReportCardModule.name).log('Redis disabled — report cards are generated in-process');
    }
    return {
      module: ReportCardModule,
      imports: [
        StudentPortalModule,
        ...(useRedis ? [BullModule.registerQueue({ name: QUEUE_REPORT_CARD_GENERATE })] : []),
      ],
      controllers: [
        ReportCommentController,
        ReportReleaseController,
        PortalReportController,
        ReportLinkController,
      ],
      providers: [
        ReportDataService,
        ReportGenerationService,
        ReportGenerationScheduler,
        ReportCommentService,
        ReportReleaseService,
        StudentReportsService,
        ...(useRedis ? [ReportCardProcessor] : []),
      ],
      exports: [StudentReportsService],
    };
  }
}
